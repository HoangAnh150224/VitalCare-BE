--comment Monitoring notes (SRS 3.9.3), patient activity status (3.8.5), and who may edit a patient.

CREATE TABLE monitoring_note (
    id            bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_monitoring_note PRIMARY KEY,
    customer_id   bigint NOT NULL CONSTRAINT fk_monitoring_note_customer REFERENCES customer (id) ON DELETE RESTRICT,
    content       text   NOT NULL,
    created_at    timestamp with time zone NOT NULL,
    created_by_id bigint,
    updated_at    timestamp with time zone,
    updated_by_id bigint,
    deleted_at    timestamp with time zone,
    deleted_by_id bigint,
    version       integer NOT NULL DEFAULT 0
);
CREATE INDEX idx_monitoring_note_customer ON monitoring_note (customer_id, created_at);

ALTER TABLE customer
    ADD COLUMN activity_status        varchar(16) NOT NULL DEFAULT 'active'
        CONSTRAINT ck_customer_activity_status CHECK (activity_status IN ('active', 'inactive', 'paused')),
    ADD COLUMN activity_reason        varchar(500),
    ADD COLUMN activity_changed_at    timestamp with time zone,
    ADD COLUMN activity_changed_by_id bigint;

INSERT INTO permissions (code, name, description, system_permission) VALUES
  ('customers:status', 'Change patient status', 'Mark a patient active, inactive or paused', TRUE);

-- SRS 3.8.4 / 3.8.5 are "Healthcare Staff" screens: the front desk and the clinic administrator.
-- customers:write had no holder at all since 022, so nobody could save a patient's details.
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON p.code IN ('customers:status', 'customers:write')
WHERE r.code IN ('MANAGER', 'CLINIC_ADMIN')
  AND NOT EXISTS (SELECT 1 FROM role_permissions x WHERE x.role_id = r.id AND x.permission_id = p.id);

