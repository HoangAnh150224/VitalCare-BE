--comment A visit is registered with a doctor for a day and gets a queue number; doctors own their working hours.

-- A doctor's week: sessions per weekday, repeating, each cut into visits.
CREATE TABLE doctor_working_hours (
    id            bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_doctor_working_hours PRIMARY KEY,
    employee_id   bigint   NOT NULL CONSTRAINT fk_doctor_working_hours_employee REFERENCES employee (id) ON DELETE CASCADE,
    day_of_week   smallint NOT NULL CONSTRAINT ck_doctor_working_hours_day CHECK (day_of_week BETWEEN 1 AND 7),
    start_time    time     NOT NULL,
    end_time      time     NOT NULL,
    visit_minutes integer  NOT NULL DEFAULT 30,
    created_at    timestamp with time zone NOT NULL,
    created_by_id bigint,
    updated_at    timestamp with time zone,
    updated_by_id bigint,
    deleted_at    timestamp with time zone,
    deleted_by_id bigint,
    version       integer NOT NULL DEFAULT 0,
    CONSTRAINT ck_doctor_working_hours_order CHECK (end_time > start_time)
);
CREATE INDEX idx_doctor_working_hours_employee ON doctor_working_hours (employee_id, day_of_week);

-- doctor_schedule is now only the time a doctor blocks; the week they work moved to the table above.
ALTER TABLE doctor_schedule DROP COLUMN status;

-- The number a registration gets: per doctor, per day, never issued twice.
ALTER TABLE appointment ADD COLUMN queue_number integer;
CREATE UNIQUE INDEX uq_appointment_doctor_day_number
    ON appointment (employee_id, appointment_date, queue_number)
    WHERE queue_number IS NOT NULL AND deleted_at IS NULL;
CREATE INDEX idx_appointment_doctor_date ON appointment (employee_id, appointment_date);

UPDATE permissions SET name = 'View doctor schedules',   description = 'See each doctor''s working hours and blocked time'
 WHERE code = 'doctor_schedules:read';
UPDATE permissions SET name = 'Manage doctor schedules', description = 'Set working hours and block time'
 WHERE code = 'doctor_schedules:write';
UPDATE permissions SET name = 'Delete blocked time',     description = 'Remove a blocked period from a doctor''s schedule'
 WHERE code = 'doctor_schedules:delete';

