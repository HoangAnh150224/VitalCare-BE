CREATE TABLE patient_feedback (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    appointment_id  BIGINT       NOT NULL REFERENCES appointment (id),
    customer_id     BIGINT       NOT NULL REFERENCES customer (id),
    clinic_id       UUID         NOT NULL REFERENCES clinic (clinic_id),
    rating          INTEGER      NOT NULL,
    comment         VARCHAR(2000),
    created_at    TIMESTAMPTZ NOT NULL,
    created_by_id BIGINT,
    updated_at    TIMESTAMPTZ,
    updated_by_id BIGINT,
    deleted_at    TIMESTAMPTZ,
    deleted_by_id BIGINT,
    version       INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT pk_patient_feedback PRIMARY KEY (id),
    CONSTRAINT ck_patient_feedback_rating CHECK (rating BETWEEN 1 AND 5)
);
CREATE UNIQUE INDEX uq_patient_feedback_visit ON patient_feedback (appointment_id) WHERE deleted_at IS NULL;

CREATE TABLE professional_license (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    employee_id     BIGINT       NOT NULL REFERENCES employee (id),
    clinic_id       UUID         REFERENCES clinic (clinic_id),
    kind            VARCHAR(16)  NOT NULL,
    title           VARCHAR(255) NOT NULL,
    license_number  VARCHAR(64)  NOT NULL,
    issuer          VARCHAR(255) NOT NULL,
    issued_on       DATE         NOT NULL,
    expires_on      DATE,
    file_key        VARCHAR(255),
    file_name       VARCHAR(255),
    file_type       VARCHAR(128),
    file_size       BIGINT,
    created_at    TIMESTAMPTZ NOT NULL,
    created_by_id BIGINT,
    updated_at    TIMESTAMPTZ,
    updated_by_id BIGINT,
    deleted_at    TIMESTAMPTZ,
    deleted_by_id BIGINT,
    version       INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT pk_professional_license PRIMARY KEY (id),
    CONSTRAINT ck_professional_license_kind CHECK (kind IN ('LICENSE', 'CERTIFICATE'))
);
CREATE INDEX idx_professional_license_employee ON professional_license (employee_id) WHERE deleted_at IS NULL;

