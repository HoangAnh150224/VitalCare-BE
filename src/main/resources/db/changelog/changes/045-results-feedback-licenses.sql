CREATE TABLE result_return (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    appointment_id  BIGINT       NOT NULL REFERENCES appointment (id),
    customer_id     BIGINT       NOT NULL REFERENCES customer (id),
    clinic_id       UUID         NOT NULL REFERENCES clinic (clinic_id),
    scheduled_at    TIMESTAMPTZ  NOT NULL,
    note            VARCHAR(500),
    status          VARCHAR(16)  NOT NULL,
    arrived_at      TIMESTAMPTZ,
    verified_by_id  BIGINT,
    missed_at       TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL,
    created_by_id BIGINT,
    updated_at    TIMESTAMPTZ,
    updated_by_id BIGINT,
    deleted_at    TIMESTAMPTZ,
    deleted_by_id BIGINT,
    version       INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT pk_result_return PRIMARY KEY (id),
    CONSTRAINT ck_result_return_status CHECK (status IN ('SCHEDULED', 'ARRIVED', 'MISSED', 'CANCELLED'))
);
CREATE INDEX idx_result_return_clinic_day ON result_return (clinic_id, scheduled_at);
CREATE INDEX idx_result_return_appointment ON result_return (appointment_id);

