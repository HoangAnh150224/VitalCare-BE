INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON
       (p.code = 'result_returns:read' AND r.code IN ('ADMIN', 'CLINIC_ADMIN', 'MANAGER', 'DOCTOR', 'NURSE', 'MEDICAL_STAFF'))
    OR (p.code = 'result_returns:write' AND r.code IN ('CLINIC_ADMIN', 'MANAGER', 'DOCTOR', 'NURSE'))
    OR (p.code IN ('my_result_returns:read', 'my_feedback:read', 'my_feedback:write') AND r.code IN ('CUSTOMER', 'PATIENT'))
    OR (p.code = 'feedback:read' AND r.code IN ('ADMIN', 'CLINIC_ADMIN', 'MANAGER', 'DOCTOR'))
    OR (p.code IN ('my_licenses:read', 'my_licenses:write') AND r.code IN ('DOCTOR', 'NURSE', 'MEDICAL_STAFF'))
    OR (p.code = 'licenses:read' AND r.code IN ('ADMIN', 'CLINIC_ADMIN'))
WHERE NOT EXISTS (SELECT 1 FROM role_permissions x WHERE x.role_id = r.id AND x.permission_id = p.id);

INSERT INTO row_level_policy (kind, role_id, resource, action, name, policy_group, description, scope, enabled, created_at)
SELECT 'SCOPE', r.id, x.resource, x.action,
       CASE WHEN r.code = 'ADMIN' THEN 'Mọi cơ sở' ELSE 'Cơ sở của mình' END, 'clinic',
       CASE WHEN r.code = 'ADMIN' THEN 'Mọi cơ sở.' ELSE 'Của cơ sở mình.' END,
       CASE WHEN r.code = 'ADMIN' THEN '{"all": []}'::jsonb
            ELSE '{"field": "clinicId", "op": "eq", "value": {"ctx": "user.clinicId"}}'::jsonb END,
       TRUE, now()
FROM roles r
CROSS JOIN (VALUES ('result_returns', 'read'), ('result_returns', 'write'), ('feedback', 'read'), ('licenses', 'read')) AS x(resource, action)
WHERE r.code IN ('ADMIN', 'CLINIC_ADMIN', 'MANAGER', 'DOCTOR', 'NURSE', 'MEDICAL_STAFF')
  AND ((x.resource = 'result_returns' AND (x.action = 'read' OR r.code IN ('CLINIC_ADMIN', 'MANAGER', 'DOCTOR', 'NURSE')))
       OR (x.resource = 'feedback' AND r.code IN ('ADMIN', 'CLINIC_ADMIN', 'MANAGER', 'DOCTOR'))
       OR (x.resource = 'licenses' AND r.code IN ('ADMIN', 'CLINIC_ADMIN')));

