--comment First-aid guidance (SRS 3.17, BR-31): articles written and reviewed by clinical staff, published for everybody, with every step and the content at that step kept.

CREATE TABLE first_aid_article (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    title              VARCHAR(200)  NOT NULL,
    category           VARCHAR(32)   NOT NULL,
    summary            VARCHAR(500)  NOT NULL,
    body               TEXT          NOT NULL,
    emergency_warning  VARCHAR(1000) NOT NULL,
    status             VARCHAR(16)   NOT NULL DEFAULT 'DRAFT',
    revision           INTEGER       NOT NULL DEFAULT 1,
    author_id          BIGINT,
    reviewer_id        BIGINT,
    review_note        VARCHAR(1000),
    published_revision INTEGER,
    published_at       TIMESTAMPTZ,
    created_at         TIMESTAMPTZ   NOT NULL,
    created_by_id      BIGINT,
    updated_at         TIMESTAMPTZ,
    updated_by_id      BIGINT,
    deleted_at         TIMESTAMPTZ,
    deleted_by_id      BIGINT,
    version            INTEGER       NOT NULL DEFAULT 0,
    CONSTRAINT pk_first_aid_article PRIMARY KEY (id),
    CONSTRAINT ck_first_aid_article_status CHECK (status IN ('DRAFT', 'PENDING_REVIEW', 'REVIEWED', 'PUBLISHED', 'ARCHIVED')),
    CONSTRAINT ck_first_aid_article_category CHECK (category IN ('RESPIRATORY', 'FAINTING', 'FEVER', 'WOUND', 'INJURY', 'ENVIRONMENT', 'GENERAL'))
);

-- Append-only: one row per step, carrying the content as it was then.
CREATE TABLE first_aid_article_history (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    article_id        BIGINT        NOT NULL,
    revision          INTEGER       NOT NULL,
    from_status       VARCHAR(16),
    to_status         VARCHAR(16)   NOT NULL,
    actor_id          BIGINT,
    note              VARCHAR(1000),
    at                TIMESTAMPTZ   NOT NULL,
    title             VARCHAR(200)  NOT NULL,
    category          VARCHAR(32)   NOT NULL,
    summary           VARCHAR(500)  NOT NULL,
    body              TEXT          NOT NULL,
    emergency_warning VARCHAR(1000) NOT NULL,
    CONSTRAINT pk_first_aid_article_history PRIMARY KEY (id),
    CONSTRAINT fk_first_aid_history_article FOREIGN KEY (article_id) REFERENCES first_aid_article (id) ON DELETE CASCADE
);
CREATE INDEX idx_first_aid_history_article ON first_aid_article_history (article_id, revision);

INSERT INTO permissions (code, name, description, system_permission) VALUES
  ('first_aid_articles:read',   'View first-aid content',   'See first-aid articles in every state, and their history', TRUE),
  ('first_aid_articles:write',  'Write first-aid content',  'Draft articles and send them for review', TRUE),
  ('first_aid_articles:review', 'Review first-aid content', 'Approve or send back, publish and archive articles', TRUE);

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON
       (p.code IN ('first_aid_articles:read', 'first_aid_articles:write')
            AND r.code IN ('ADMIN', 'CLINIC_ADMIN', 'DOCTOR', 'NURSE', 'MEDICAL_STAFF'))
    OR (p.code = 'first_aid_articles:review' AND r.code IN ('ADMIN', 'CLINIC_ADMIN', 'DOCTOR'))
WHERE NOT EXISTS (SELECT 1 FROM role_permissions x WHERE x.role_id = r.id AND x.permission_id = p.id);

