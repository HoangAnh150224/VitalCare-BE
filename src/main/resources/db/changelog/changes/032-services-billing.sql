INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON
       (p.code = 'medical_services:read'  AND r.code IN ('ADMIN', 'DOCTOR', 'NURSE', 'MANAGER', 'CLINIC_ADMIN'))
    OR (p.code = 'medical_services:write' AND r.code IN ('ADMIN'))
    OR (p.code = 'service_orders:read'    AND r.code IN ('DOCTOR', 'NURSE', 'MANAGER'))
    OR (p.code = 'service_orders:write'   AND r.code IN ('DOCTOR', 'NURSE'))
    OR (p.code = 'invoices:read'          AND r.code IN ('MANAGER', 'CLINIC_ADMIN'))
    OR (p.code = 'invoices:write'         AND r.code IN ('MANAGER'))
    OR (p.code = 'invoices:report'        AND r.code IN ('CLINIC_ADMIN'))
WHERE NOT EXISTS (SELECT 1 FROM role_permissions x WHERE x.role_id = r.id AND x.permission_id = p.id);

