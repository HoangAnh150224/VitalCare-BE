-- A service a doctor orders during an encounter, and its result.
CREATE TABLE service_order (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_service_order PRIMARY KEY,
    encounter_id       bigint NOT NULL CONSTRAINT fk_service_order_encounter REFERENCES clinical_encounter (id) ON DELETE RESTRICT,
    customer_id        bigint NOT NULL CONSTRAINT fk_service_order_customer REFERENCES customer (id) ON DELETE RESTRICT,
    clinic_id          uuid   NOT NULL CONSTRAINT fk_service_order_clinic REFERENCES clinic (clinic_id) ON DELETE RESTRICT,
    service_id         bigint NOT NULL CONSTRAINT fk_service_order_service REFERENCES clinic_service (id) ON DELETE RESTRICT,
    -- The price when ordered: the bill follows this, not a later price change.
    unit_price         numeric(19, 4) NOT NULL,
    instruction        varchar(1000),
    status             varchar(16) NOT NULL DEFAULT 'ORDERED'
        CONSTRAINT ck_service_order_status CHECK (status IN ('ORDERED', 'IN_PROGRESS', 'RESULT_READY', 'REVIEWED', 'CANCELLED')),
    expected_result_at timestamp with time zone,
    performed_by_id    bigint,
    started_at         timestamp with time zone,
    result_text        text,
    result_at          timestamp with time zone,
    reviewed_by_id     bigint,
    reviewed_at        timestamp with time zone,
    cancelled_at       timestamp with time zone,
    cancel_reason      varchar(500),
    created_at         timestamp with time zone NOT NULL,
    created_by_id      bigint,
    updated_at         timestamp with time zone,
    updated_by_id      bigint,
    deleted_at         timestamp with time zone,
    deleted_by_id      bigint,
    version            integer NOT NULL DEFAULT 0
);
CREATE INDEX idx_service_order_encounter ON service_order (encounter_id);
CREATE INDEX idx_service_order_clinic_status ON service_order (clinic_id, status, created_at);

-- A file attached to a result: a lab sheet, an image. Stored outside the database under storage_key.
CREATE TABLE service_order_file (
    id            bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_service_order_file PRIMARY KEY,
    order_id      bigint NOT NULL CONSTRAINT fk_service_order_file_order REFERENCES service_order (id) ON DELETE RESTRICT,
    original_name varchar(255) NOT NULL,
    content_type  varchar(100) NOT NULL,
    size_bytes    bigint NOT NULL,
    storage_key   varchar(255) NOT NULL CONSTRAINT uq_service_order_file_key UNIQUE,
    created_at    timestamp with time zone NOT NULL,
    created_by_id bigint,
    updated_at    timestamp with time zone,
    updated_by_id bigint,
    deleted_at    timestamp with time zone,
    deleted_by_id bigint,
    version       integer NOT NULL DEFAULT 0
);
CREATE INDEX idx_service_order_file_order ON service_order_file (order_id);

-- One bill per encounter: the examination and its services.
ALTER TABLE invoice
    ADD COLUMN clinic_id      uuid CONSTRAINT fk_invoice_clinic REFERENCES clinic (clinic_id) ON DELETE RESTRICT,
    ADD COLUMN appointment_id bigint CONSTRAINT fk_invoice_appointment REFERENCES appointment (id) ON DELETE SET NULL,
    ADD COLUMN paid_at        timestamp with time zone,
    ADD CONSTRAINT ck_invoice_status CHECK (status IN ('UNPAID', 'PAID', 'CANCELLED')),
    ADD CONSTRAINT uq_invoice_number UNIQUE (invoice_number);
CREATE UNIQUE INDEX uq_invoice_encounter ON invoice (clinical_encounter_id) WHERE deleted_at IS NULL;
CREATE INDEX idx_invoice_clinic_issued ON invoice (clinic_id, issued_at);
CREATE INDEX idx_invoice_appointment ON invoice (appointment_id);

-- A payment attempt. payment_method is the channel; transaction_code is the
-- reference sent to the gateway (vnp_TxnRef) or written on a counter receipt.
ALTER TABLE payment
    ADD COLUMN response_code varchar(8),
    ADD COLUMN provider_ref  varchar(64),
    ADD CONSTRAINT ck_payment_status CHECK (status IN ('PENDING', 'PAID', 'FAILED')),
    ADD CONSTRAINT ck_payment_method CHECK (payment_method IN ('CASH', 'BANK_TRANSFER', 'VNPAY')),
    ADD CONSTRAINT uq_payment_transaction_code UNIQUE (transaction_code);
CREATE INDEX idx_payment_invoice ON payment (invoice_id);

