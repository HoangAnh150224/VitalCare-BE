-- A clinic's rooms. One patient at most is in a room: current_appointment_id is
-- unique, and appointment carries the same fact the other way round (below).
CREATE TABLE exam_room (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_exam_room PRIMARY KEY,
    clinic_id              uuid        NOT NULL CONSTRAINT fk_exam_room_clinic REFERENCES clinic (clinic_id) ON DELETE RESTRICT,
    code                   varchar(20) NOT NULL,
    name                   varchar(100),
    status                 varchar(16) NOT NULL DEFAULT 'AVAILABLE'
        CONSTRAINT ck_exam_room_status CHECK (status IN ('AVAILABLE', 'OCCUPIED', 'PAUSED')),
    current_appointment_id bigint CONSTRAINT uq_exam_room_current_appointment UNIQUE
        CONSTRAINT fk_exam_room_current_appointment REFERENCES appointment (id) ON DELETE SET NULL,
    created_at             timestamp with time zone NOT NULL,
    created_by_id          bigint,
    updated_at             timestamp with time zone,
    updated_by_id          bigint,
    deleted_at             timestamp with time zone,
    deleted_by_id          bigint,
    version                integer NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX uq_exam_room_clinic_code ON exam_room (clinic_id, lower(code)) WHERE deleted_at IS NULL;

-- The room a doctor sits in for one session of their week: what "a shift" is here.
ALTER TABLE doctor_working_hours
    ADD COLUMN exam_room_id bigint CONSTRAINT fk_working_hours_exam_room REFERENCES exam_room (id) ON DELETE SET NULL;
CREATE INDEX idx_working_hours_room_day ON doctor_working_hours (exam_room_id, day_of_week);

-- Where the visit took place, when the patient was called in, and when they
-- were last passed over for not being there (they wait behind those never called).
ALTER TABLE appointment
    ADD COLUMN exam_room_id bigint CONSTRAINT fk_appointment_exam_room REFERENCES exam_room (id) ON DELETE SET NULL,
    ADD COLUMN called_at    timestamp with time zone,
    ADD COLUMN skipped_at   timestamp with time zone;
-- The last word on "one patient per room", whatever the application does.
CREATE UNIQUE INDEX uq_appointment_in_exam_room ON appointment (exam_room_id)
    WHERE status = 'IN_EXAM' AND deleted_at IS NULL;
-- The next-in-line lookup: one doctor's checked-in visits of one day, in call order.
CREATE INDEX idx_appointment_doctor_day_queue ON appointment (employee_id, appointment_date, status, queue_number);

INSERT INTO permissions (code, name, description, system_permission) VALUES
  ('exam_rooms:read',    'View exam rooms',    'See a clinic''s examination rooms and who is in them', TRUE),
  ('exam_rooms:write',   'Manage exam rooms',  'Create and rename a clinic''s examination rooms', TRUE),
  ('exam_rooms:operate', 'Operate exam rooms', 'Call the next patient, pass one over, pause or reopen a room', TRUE);

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON
       (p.code = 'exam_rooms:read'    AND r.code IN ('DOCTOR', 'NURSE', 'MANAGER', 'CLINIC_ADMIN'))
    OR (p.code = 'exam_rooms:write'   AND r.code IN ('CLINIC_ADMIN'))
    OR (p.code = 'exam_rooms:operate' AND r.code IN ('DOCTOR', 'NURSE', 'MANAGER'))
WHERE NOT EXISTS (SELECT 1 FROM role_permissions x WHERE x.role_id = r.id AND x.permission_id = p.id);

-- A room belongs to its clinic (BR-04): staff read and work their own clinic's rooms.
INSERT INTO row_level_policy (kind, role_id, resource, action, name, policy_group, description, scope, enabled, created_at)
SELECT 'SCOPE', r.id, 'exam_rooms', a.action, 'Cơ sở của mình', 'clinic',
       'Phòng khám tại cơ sở của mình.',
       '{"field": "clinicId", "op": "eq", "value": {"ctx": "user.clinicId"}}'::jsonb, TRUE, now()
FROM roles r
CROSS JOIN (VALUES ('read'), ('write')) AS a(action)
WHERE r.code IN ('DOCTOR', 'NURSE', 'MANAGER', 'CLINIC_ADMIN');

