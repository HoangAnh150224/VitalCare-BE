INSERT INTO permissions (code, name, description, system_permission) VALUES
  ('alert_rules:read',  'View alert rules',   'See the thresholds that raise alerts', TRUE),
  ('alert_rules:write', 'Manage alert rules', 'Create and change clinic and patient alert rules', TRUE),
  ('alerts:read',       'View alerts',        'See alerts raised from patients'' vital signs', TRUE),
  ('alerts:write',      'Handle alerts',      'Acknowledge, resolve or dismiss alerts and add handling notes', TRUE),
  ('my_alerts:read',    'View own alerts',    'See the alerts raised for one''s own profiles', TRUE);

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON
       (p.code IN ('alert_rules:read', 'alerts:read') AND r.code IN ('ADMIN', 'CLINIC_ADMIN', 'MANAGER', 'DOCTOR', 'NURSE', 'MEDICAL_STAFF'))
    OR (p.code = 'alert_rules:write' AND r.code IN ('ADMIN', 'CLINIC_ADMIN', 'DOCTOR'))
    OR (p.code = 'alerts:write' AND r.code IN ('ADMIN', 'CLINIC_ADMIN', 'DOCTOR', 'NURSE', 'MEDICAL_STAFF'))
    OR (p.code = 'my_alerts:read' AND r.code IN ('CUSTOMER', 'PATIENT'))
WHERE NOT EXISTS (SELECT 1 FROM role_permissions x WHERE x.role_id = r.id AND x.permission_id = p.id);

INSERT INTO row_level_policy (kind, role_id, resource, action, name, policy_group, description, scope, enabled, created_at)
SELECT 'SCOPE', r.id, x.resource, x.action,
       CASE WHEN r.code = 'ADMIN' THEN 'Mọi cơ sở' ELSE 'Cơ sở của mình' END, 'clinic',
       CASE WHEN r.code = 'ADMIN' THEN 'Mọi cơ sở.' ELSE 'Của cơ sở mình.' END,
       CASE WHEN r.code = 'ADMIN' THEN '{"all": []}'::jsonb
            ELSE '{"field": "clinicId", "op": "eq", "value": {"ctx": "user.clinicId"}}'::jsonb END,
       TRUE, now()
FROM roles r
CROSS JOIN (VALUES ('alert_rules', 'read'), ('alert_rules', 'write'), ('alerts', 'read'), ('alerts', 'write')) AS x(resource, action)
WHERE r.code IN ('ADMIN', 'CLINIC_ADMIN', 'MANAGER', 'DOCTOR', 'NURSE', 'MEDICAL_STAFF')
  AND (x.action = 'read'
       OR (x.resource = 'alert_rules' AND r.code IN ('ADMIN', 'CLINIC_ADMIN', 'DOCTOR'))
       OR (x.resource = 'alerts' AND r.code IN ('ADMIN', 'CLINIC_ADMIN', 'DOCTOR', 'NURSE', 'MEDICAL_STAFF')));

