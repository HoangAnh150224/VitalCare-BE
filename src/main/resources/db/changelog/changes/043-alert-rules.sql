-- Action History: every step of an alert, and every abnormal reading that fed it.
CREATE TABLE alert_action (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    alert_id      BIGINT       NOT NULL REFERENCES alert (id),
    action        VARCHAR(32)  NOT NULL,
    vital_sign_id BIGINT       REFERENCES vital_signs (id),
    value         NUMERIC(6,2),
    severity      VARCHAR(16),
    actor_id      BIGINT,
    actor_name    VARCHAR(255),
    note          TEXT,
    occurred_at   TIMESTAMPTZ  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    created_by_id BIGINT,
    updated_at    TIMESTAMPTZ,
    updated_by_id BIGINT,
    deleted_at    TIMESTAMPTZ,
    deleted_by_id BIGINT,
    version       INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT pk_alert_action PRIMARY KEY (id),
    CONSTRAINT ck_alert_action CHECK (action IN ('TRIGGERED', 'REPEATED', 'SEVERITY_RAISED', 'ACKNOWLEDGED', 'NOTE',
                                                 'RESOLVED', 'DISMISSED', 'NOTIFIED', 'ESCALATED'))
);
CREATE INDEX idx_alert_action_alert ON alert_action (alert_id, occurred_at);
CREATE INDEX idx_alert_action_reading ON alert_action (vital_sign_id) WHERE vital_sign_id IS NOT NULL;

