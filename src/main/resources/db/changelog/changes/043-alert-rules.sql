CREATE TABLE alert_rule (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    clinic_id     UUID         NOT NULL REFERENCES clinic (clinic_id),
    customer_id   BIGINT       REFERENCES customer (id),
    name          VARCHAR(255) NOT NULL,
    metric        VARCHAR(32)  NOT NULL,
    operator      VARCHAR(8)   NOT NULL,
    threshold     NUMERIC(6,2) NOT NULL,
    severity      VARCHAR(16)  NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    note          VARCHAR(1000),
    created_at    TIMESTAMPTZ  NOT NULL,
    created_by_id BIGINT,
    updated_at    TIMESTAMPTZ,
    updated_by_id BIGINT,
    deleted_at    TIMESTAMPTZ,
    deleted_by_id BIGINT,
    version       INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT pk_alert_rule PRIMARY KEY (id),
    CONSTRAINT ck_alert_rule_metric CHECK (metric IN ('HEART_RATE', 'SPO2', 'SKIN_TEMPERATURE')),
    CONSTRAINT ck_alert_rule_operator CHECK (operator IN ('BELOW', 'ABOVE')),
    CONSTRAINT ck_alert_rule_severity CHECK (severity IN ('WARNING', 'CRITICAL'))
);
CREATE INDEX idx_alert_rule_clinic ON alert_rule (clinic_id) WHERE deleted_at IS NULL;
CREATE INDEX idx_alert_rule_customer ON alert_rule (customer_id) WHERE deleted_at IS NULL;

