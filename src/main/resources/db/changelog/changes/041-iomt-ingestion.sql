-- What a device last said about itself, and the secret it signs in to MQTT with (its hash only).
ALTER TABLE medical_device
    ADD COLUMN battery_level     INTEGER,
    ADD COLUMN firmware_version  VARCHAR(64),
    ADD COLUMN connectivity      VARCHAR(16) NOT NULL DEFAULT 'OFFLINE',
    ADD COLUMN last_sync_at      TIMESTAMPTZ,
    ADD COLUMN token_hash        VARCHAR(64),
    ADD COLUMN paired_at         TIMESTAMPTZ,
    ADD COLUMN paired_by_user_id BIGINT,
    ADD CONSTRAINT ck_medical_device_connectivity CHECK (connectivity IN ('ONLINE', 'OFFLINE')),
    ADD CONSTRAINT ck_medical_device_battery CHECK (battery_level IS NULL OR battery_level BETWEEN 0 AND 100);

-- One sitting with the device (FE-03): started, readings taken, completed or cancelled.
CREATE TABLE measurement_session (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    device_id            BIGINT      NOT NULL REFERENCES medical_device (id),
    customer_id          BIGINT      NOT NULL REFERENCES customer (id),
    device_assignment_id BIGINT      REFERENCES device_assignment (id),
    client_session_id    VARCHAR(64) NOT NULL,
    started_at           TIMESTAMPTZ NOT NULL,
    ended_at             TIMESTAMPTZ,
    status               VARCHAR(16) NOT NULL DEFAULT 'IN_PROGRESS',
    created_at           TIMESTAMPTZ NOT NULL,
    created_by_id        BIGINT,
    updated_at           TIMESTAMPTZ,
    updated_by_id        BIGINT,
    deleted_at           TIMESTAMPTZ,
    deleted_by_id        BIGINT,
    version              INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT pk_measurement_session PRIMARY KEY (id),
    CONSTRAINT uq_measurement_session_client UNIQUE (device_id, client_session_id),
    CONSTRAINT ck_measurement_session_status CHECK (status IN ('IN_PROGRESS', 'COMPLETED', 'CANCELLED'))
);
CREATE INDEX idx_measurement_session_customer ON measurement_session (customer_id, started_at DESC);

-- A reading: SpO2, heart rate and wrist skin temperature (the existing temperature column).
-- client_record_id is the device's own id for it: sent twice, it is stored once.
ALTER TABLE vital_signs
    ADD COLUMN session_id        BIGINT REFERENCES measurement_session (id),
    ADD COLUMN client_record_id  VARCHAR(64),
    ADD COLUMN source            VARCHAR(16) NOT NULL DEFAULT 'REST',
    ADD COLUMN validation_status VARCHAR(16) NOT NULL DEFAULT 'VALID',
    ADD COLUMN validation_error  VARCHAR(255),
    ADD CONSTRAINT ck_vital_signs_validation CHECK (validation_status IN ('VALID', 'INVALID')),
    ADD CONSTRAINT ck_vital_signs_source CHECK (source IN ('REST', 'MQTT', 'SIMULATOR'));
CREATE UNIQUE INDEX uq_vital_signs_client_record ON vital_signs (device_id, client_record_id)
    WHERE client_record_id IS NOT NULL;
CREATE INDEX idx_vital_signs_customer_measured ON vital_signs (customer_id, measured_at DESC);
CREATE INDEX idx_vital_signs_device_measured ON vital_signs (device_id, measured_at DESC);

-- Every upload (FE-06): how many records came, how many were kept, duplicated or refused.
CREATE TABLE sync_batch (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    device_id         BIGINT      REFERENCES medical_device (id),
    clinic_id         UUID        REFERENCES clinic (clinic_id),
    customer_id       BIGINT      REFERENCES customer (id),
    client_batch_id   VARCHAR(64),
    source            VARCHAR(16) NOT NULL,
    received_at       TIMESTAMPTZ NOT NULL,
    record_count      INTEGER     NOT NULL DEFAULT 0,
    accepted_count    INTEGER     NOT NULL DEFAULT 0,
    duplicate_count   INTEGER     NOT NULL DEFAULT 0,
    rejected_count    INTEGER     NOT NULL DEFAULT 0,
    pending_on_device INTEGER,
    status            VARCHAR(16) NOT NULL,
    error             VARCHAR(500),
    created_at        TIMESTAMPTZ NOT NULL,
    created_by_id     BIGINT,
    updated_at        TIMESTAMPTZ,
    updated_by_id     BIGINT,
    deleted_at        TIMESTAMPTZ,
    deleted_by_id     BIGINT,
    version           INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT pk_sync_batch PRIMARY KEY (id),
    CONSTRAINT ck_sync_batch_status CHECK (status IN ('SUCCESS', 'PARTIAL', 'FAILED')),
    CONSTRAINT ck_sync_batch_source CHECK (source IN ('REST', 'MQTT', 'SIMULATOR'))
);
CREATE INDEX idx_sync_batch_device ON sync_batch (device_id, received_at DESC);
CREATE INDEX idx_sync_batch_clinic ON sync_batch (clinic_id, received_at DESC);

-- A record refused, kept as it came so it can be looked at and tried again.
CREATE TABLE sync_failure (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    batch_id         BIGINT       NOT NULL REFERENCES sync_batch (id) ON DELETE CASCADE,
    device_id        BIGINT       REFERENCES medical_device (id),
    clinic_id        UUID         REFERENCES clinic (clinic_id),
    client_record_id VARCHAR(64),
    payload          JSONB        NOT NULL,
    reason           VARCHAR(255) NOT NULL,
    status           VARCHAR(16)  NOT NULL DEFAULT 'OPEN',
    attempts         INTEGER      NOT NULL DEFAULT 1,
    last_attempt_at  TIMESTAMPTZ  NOT NULL,
    resolved_at      TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL,
    created_by_id    BIGINT,
    updated_at       TIMESTAMPTZ,
    updated_by_id    BIGINT,
    deleted_at       TIMESTAMPTZ,
    deleted_by_id    BIGINT,
    version          INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT pk_sync_failure PRIMARY KEY (id),
    CONSTRAINT ck_sync_failure_status CHECK (status IN ('OPEN', 'RESOLVED', 'DISCARDED'))
);
CREATE INDEX idx_sync_failure_open ON sync_failure (clinic_id, status, last_attempt_at DESC);

INSERT INTO permissions (code, name, description, system_permission) VALUES
  ('device_syncs:read',  'View device synchronisation', 'See uploads from devices, their results and refused records', TRUE),
  ('sync_failures:read', 'View refused readings', 'See the readings an upload could not take in, and why', TRUE),
  ('sync_failures:write', 'Retry refused readings', 'Try refused readings again or set them aside', TRUE),
  ('vital_signs:read',   'View vital signs', 'See patients'' measured SpO2, heart rate and skin temperature', TRUE),
  ('devices:operate',    'Operate devices', 'Issue a device''s MQTT secret and run the device simulator', TRUE),
  ('my_devices:read',    'View own devices', 'See the monitoring devices handed to one''s own profiles', TRUE),
  ('my_devices:write',   'Use own devices', 'Pair a device and upload its readings', TRUE);

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON
       (p.code IN ('device_syncs:read', 'sync_failures:read', 'vital_signs:read') AND r.code IN ('ADMIN', 'CLINIC_ADMIN', 'MANAGER', 'DOCTOR', 'NURSE', 'MEDICAL_STAFF'))
    OR (p.code = 'sync_failures:write' AND r.code IN ('ADMIN', 'CLINIC_ADMIN', 'MANAGER', 'NURSE', 'MEDICAL_STAFF'))
    -- Whoever registers and hands out the clinic's devices (devices:write): the clinic administrator and the desk.
    OR (p.code = 'devices:operate' AND r.code IN ('CLINIC_ADMIN', 'MANAGER'))
    OR (p.code LIKE 'my_devices:%' AND r.code IN ('CUSTOMER', 'PATIENT'))
WHERE NOT EXISTS (SELECT 1 FROM role_permissions x WHERE x.role_id = r.id AND x.permission_id = p.id);

-- Sync records belong to the device's clinic; the system administrator sees every clinic's.
INSERT INTO row_level_policy (kind, role_id, resource, action, name, policy_group, description, scope, enabled, created_at)
SELECT 'SCOPE', r.id, x.resource, x.action,
       CASE WHEN r.code = 'ADMIN' THEN 'Mọi cơ sở' ELSE 'Cơ sở của mình' END, 'clinic',
       CASE WHEN r.code = 'ADMIN' THEN 'Đồng bộ của mọi cơ sở.' ELSE 'Đồng bộ của thiết bị tại cơ sở của mình.' END,
       CASE WHEN r.code = 'ADMIN' THEN '{"all": []}'::jsonb
            ELSE '{"field": "clinicId", "op": "eq", "value": {"ctx": "user.clinicId"}}'::jsonb END,
       TRUE, now()
FROM roles r
CROSS JOIN (VALUES ('device_syncs', 'read'), ('sync_failures', 'read'), ('sync_failures', 'write')) AS x(resource, action)
WHERE r.code IN ('ADMIN', 'CLINIC_ADMIN', 'MANAGER', 'DOCTOR', 'NURSE', 'MEDICAL_STAFF')
  AND (x.action = 'read' OR r.code IN ('ADMIN', 'CLINIC_ADMIN', 'MANAGER', 'NURSE', 'MEDICAL_STAFF'));

