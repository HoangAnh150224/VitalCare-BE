--comment BF-13 / SRS 3.18.9-3.18.10: a member of staff's membership of a clinic, with its history (joined, moved, ended), and the clinic-level roles a clinic administrator gives them, apart from the kind of staff they are.

CREATE TABLE staff_membership (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    employee_id   BIGINT       NOT NULL REFERENCES employee (id),
    clinic_id     UUID         NOT NULL REFERENCES clinic (clinic_id),
    status        VARCHAR(16)  NOT NULL,
    started_at    TIMESTAMPTZ  NOT NULL,
    ended_at      TIMESTAMPTZ,
    end_reason    VARCHAR(500),
    created_at    TIMESTAMPTZ NOT NULL,
    created_by_id BIGINT,
    updated_at    TIMESTAMPTZ,
    updated_by_id BIGINT,
    deleted_at    TIMESTAMPTZ,
    deleted_by_id BIGINT,
    version       INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT pk_staff_membership PRIMARY KEY (id),
    CONSTRAINT ck_staff_membership_status CHECK (status IN ('ACTIVE', 'ENDED'))
);
CREATE UNIQUE INDEX uq_staff_membership_active ON staff_membership (employee_id) WHERE status = 'ACTIVE' AND deleted_at IS NULL;
CREATE INDEX idx_staff_membership_clinic ON staff_membership (clinic_id) WHERE deleted_at IS NULL;

-- Everybody already on staff has had their membership since they joined; somebody who left has ended theirs.
INSERT INTO staff_membership (employee_id, clinic_id, status, started_at, ended_at, end_reason, created_at)
SELECT e.id, e.clinic_id, CASE WHEN e.status = 'ACTIVE' THEN 'ACTIVE' ELSE 'ENDED' END, e.created_at,
       CASE WHEN e.status = 'ACTIVE' THEN NULL ELSE coalesce(e.updated_at, e.created_at) END,
       CASE WHEN e.status = 'ACTIVE' THEN NULL ELSE 'Đã nghỉ (trước khi có lịch sử thành viên)' END, now()
FROM employee e
WHERE e.clinic_id IS NOT NULL AND e.deleted_at IS NULL;

INSERT INTO permissions (code, name, description, system_permission) VALUES
  ('staff_memberships:read',     'View staff memberships',  'See which clinic a member of staff belongs to, and since when', TRUE),
  ('staff_memberships:write',    'End staff memberships',   'End a member of staff''s membership of the clinic', TRUE),
  ('staff_memberships:transfer', 'Move staff between clinics', 'Move a member of staff to another clinic', TRUE),
  ('clinic_roles:read',  'View clinic-level roles',   'See the roles staff hold at the clinic and what each allows', TRUE),
  ('clinic_roles:write', 'Assign clinic-level roles', 'Give or take away a member of staff''s roles at the clinic', TRUE);

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON
       (p.code IN ('staff_memberships:read', 'staff_memberships:write', 'clinic_roles:read', 'clinic_roles:write')
        AND r.code IN ('ADMIN', 'CLINIC_ADMIN'))
    OR (p.code = 'staff_memberships:transfer' AND r.code = 'ADMIN')
WHERE NOT EXISTS (SELECT 1 FROM role_permissions x WHERE x.role_id = r.id AND x.permission_id = p.id);

