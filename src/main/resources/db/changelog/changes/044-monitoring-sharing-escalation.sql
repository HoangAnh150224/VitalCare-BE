--comment BF-04 monitoring orders with the patient's consent (a device is handed out only under an accepted one); BF-06 sharing with at most two caregivers, emergency notices to them and the call/SMS escalation after 30 s, all on record.

CREATE TABLE monitoring_order (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_id       BIGINT      NOT NULL REFERENCES customer (id),
    encounter_id      BIGINT      REFERENCES clinical_encounter (id),
    clinic_id         UUID        NOT NULL REFERENCES clinic (clinic_id),
    ordered_by_id     BIGINT,
    ordered_by_name   VARCHAR(255),
    reason            VARCHAR(1000) NOT NULL,
    decision          VARCHAR(16) NOT NULL,
    consent_note      VARCHAR(1000),
    decided_at        TIMESTAMPTZ NOT NULL,
    status            VARCHAR(16) NOT NULL,
    ended_at          TIMESTAMPTZ,
    ended_by_id       BIGINT,
    end_note          VARCHAR(1000),
    created_at    TIMESTAMPTZ NOT NULL,
    created_by_id BIGINT,
    updated_at    TIMESTAMPTZ,
    updated_by_id BIGINT,
    deleted_at    TIMESTAMPTZ,
    deleted_by_id BIGINT,
    version       INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT pk_monitoring_order PRIMARY KEY (id),
    CONSTRAINT ck_monitoring_order_decision CHECK (decision IN ('ACCEPTED', 'DECLINED')),
    CONSTRAINT ck_monitoring_order_status CHECK (status IN ('ACTIVE', 'DECLINED', 'ENDED'))
);
CREATE INDEX idx_monitoring_order_customer ON monitoring_order (customer_id, decided_at DESC);

CREATE TABLE sharing_permission (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_id         BIGINT      NOT NULL REFERENCES customer (id),
    caregiver_user_id   BIGINT      NOT NULL REFERENCES users (id),
    share_vitals        BOOLEAN     NOT NULL DEFAULT TRUE,
    share_alerts        BOOLEAN     NOT NULL DEFAULT TRUE,
    share_appointments  BOOLEAN     NOT NULL DEFAULT FALSE,
    emergency_phone     VARCHAR(20) NOT NULL,
    expires_at          TIMESTAMPTZ,
    note                VARCHAR(500),
    status              VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    revoked_at          TIMESTAMPTZ,
    revoked_by_id       BIGINT,
    created_at    TIMESTAMPTZ NOT NULL,
    created_by_id BIGINT,
    updated_at    TIMESTAMPTZ,
    updated_by_id BIGINT,
    deleted_at    TIMESTAMPTZ,
    deleted_by_id BIGINT,
    version       INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT pk_sharing_permission PRIMARY KEY (id),
    CONSTRAINT ck_sharing_permission_status CHECK (status IN ('ACTIVE', 'REVOKED'))
);
CREATE INDEX idx_sharing_permission_customer ON sharing_permission (customer_id) WHERE deleted_at IS NULL;
CREATE INDEX idx_sharing_permission_caregiver ON sharing_permission (caregiver_user_id) WHERE deleted_at IS NULL;

-- A critical alert told to one caregiver; escalated by call and SMS if not acknowledged in time.
CREATE TABLE emergency_notice (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    alert_id              BIGINT      NOT NULL REFERENCES alert (id),
    sharing_permission_id BIGINT      REFERENCES sharing_permission (id),
    customer_id           BIGINT      NOT NULL REFERENCES customer (id),
    recipient_user_id     BIGINT      NOT NULL REFERENCES users (id),
    emergency_phone       VARCHAR(20),
    notified_at           TIMESTAMPTZ NOT NULL,
    acknowledged_at       TIMESTAMPTZ,
    escalated_at          TIMESTAMPTZ,
    status                VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    created_at    TIMESTAMPTZ NOT NULL,
    created_by_id BIGINT,
    updated_at    TIMESTAMPTZ,
    updated_by_id BIGINT,
    deleted_at    TIMESTAMPTZ,
    deleted_by_id BIGINT,
    version       INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT pk_emergency_notice PRIMARY KEY (id),
    CONSTRAINT ck_emergency_notice_status CHECK (status IN ('PENDING', 'ACKNOWLEDGED', 'ESCALATED'))
);
CREATE INDEX idx_emergency_notice_pending ON emergency_notice (notified_at) WHERE status = 'PENDING';
CREATE INDEX idx_emergency_notice_recipient ON emergency_notice (recipient_user_id, notified_at DESC);

-- Caregiver Escalation and Call Log: every call placed and SMS sent.
CREATE TABLE escalation_call (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    notice_id  BIGINT       NOT NULL REFERENCES emergency_notice (id),
    alert_id   BIGINT       NOT NULL REFERENCES alert (id),
    channel    VARCHAR(8)   NOT NULL,
    phone      VARCHAR(20)  NOT NULL,
    outcome    VARCHAR(16)  NOT NULL,
    detail     VARCHAR(500),
    placed_at  TIMESTAMPTZ  NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL,
    created_by_id BIGINT,
    updated_at    TIMESTAMPTZ,
    updated_by_id BIGINT,
    deleted_at    TIMESTAMPTZ,
    deleted_by_id BIGINT,
    version       INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT pk_escalation_call PRIMARY KEY (id),
    CONSTRAINT ck_escalation_call_channel CHECK (channel IN ('CALL', 'SMS'))
);
CREATE INDEX idx_escalation_call_alert ON escalation_call (alert_id, placed_at);

