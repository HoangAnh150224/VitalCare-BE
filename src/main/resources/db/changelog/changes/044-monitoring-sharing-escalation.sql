INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON
       (p.code = 'monitoring_orders:read' AND r.code IN ('ADMIN', 'CLINIC_ADMIN', 'MANAGER', 'DOCTOR', 'NURSE', 'MEDICAL_STAFF'))
    OR (p.code = 'monitoring_orders:write' AND r.code IN ('ADMIN', 'CLINIC_ADMIN', 'DOCTOR'))
    OR (p.code IN ('my_sharing:read', 'my_sharing:write', 'shared_patients:read', 'emergency_alerts:read', 'emergency_alerts:write')
        AND r.code IN ('CUSTOMER', 'PATIENT'))
    OR (p.code = 'escalations:read' AND r.code IN ('ADMIN', 'CLINIC_ADMIN', 'DOCTOR', 'NURSE', 'MEDICAL_STAFF'))
WHERE NOT EXISTS (SELECT 1 FROM role_permissions x WHERE x.role_id = r.id AND x.permission_id = p.id);

INSERT INTO row_level_policy (kind, role_id, resource, action, name, policy_group, description, scope, enabled, created_at)
SELECT 'SCOPE', r.id, 'monitoring_orders', x.action,
       CASE WHEN r.code = 'ADMIN' THEN 'Mọi cơ sở' ELSE 'Cơ sở của mình' END, 'clinic',
       CASE WHEN r.code = 'ADMIN' THEN 'Mọi cơ sở.' ELSE 'Của cơ sở mình.' END,
       CASE WHEN r.code = 'ADMIN' THEN '{"all": []}'::jsonb
            ELSE '{"field": "clinicId", "op": "eq", "value": {"ctx": "user.clinicId"}}'::jsonb END,
       TRUE, now()
FROM roles r
CROSS JOIN (VALUES ('read'), ('write')) AS x(action)
WHERE r.code IN ('ADMIN', 'CLINIC_ADMIN', 'MANAGER', 'DOCTOR', 'NURSE', 'MEDICAL_STAFF')
  AND (x.action = 'read' OR r.code IN ('ADMIN', 'CLINIC_ADMIN', 'DOCTOR'));

